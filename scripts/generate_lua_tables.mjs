#!/usr/bin/env node
/**
 * Converts shared/classes.json and shared/registry-addons.json
 * into Lua table format for the WoW addon (addon/Data.lua).
 *
 * Usage: node scripts/generate_lua_tables.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const sharedDir = resolve(__dirname, '..', 'shared');

// Read the classes JSON
const classesJson = readFileSync(resolve(sharedDir, 'classes.json'), 'utf-8');
const classesData = JSON.parse(classesJson);

// Read addon registry (generated from shared/addon-recommendations.ts REGISTRY_ADDONS)
const registryJson = readFileSync(resolve(sharedDir, 'registry-addons.json'), 'utf-8');
const registryAddons = JSON.parse(registryJson);

function escapeLuaString(str) {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function generateClassTable(classInfo) {
  const classId = classInfo.id;
  let lua = `  ["${escapeLuaString(classId)}"] = {\n`;
  lua += `    name = "${escapeLuaString(classInfo.name)}",\n`;
  lua += `    icon = "${escapeLuaString(classInfo.icon)}",\n`;
  lua += `    specs = {\n`;

  for (const spec of classInfo.specs) {
    const specId = spec.id;
    lua += `      ["${escapeLuaString(specId)}"] = {\n`;
    lua += `        name = "${escapeLuaString(spec.name)}",\n`;
    lua += `        order = ${spec.order},\n`;
    lua += `      },\n`;
  }

  lua += `    },\n`;
  lua += `  },\n`;
  return lua;
}

function generateAddonEntry(key, addon) {
  let lua = `  ["${escapeLuaString(key)}"] = {\n`;
  lua += `    name = "${escapeLuaString(addon.name)}",\n`;
  lua += `    priority = "${escapeLuaString(addon.priority)}",\n`;
  lua += `    description = "${escapeLuaString(addon.description)}",\n`;

  if (addon.url) {
    lua += `    url = "${escapeLuaString(addon.url)}",\n`;
  }

  if (addon.savedVariableName) {
    lua += `    savedVariableName = "${escapeLuaString(addon.savedVariableName)}",\n`;
  }

  // Generate default settings as a nested table
  if (addon.defaultSettings && Object.keys(addon.defaultSettings).length > 0) {
    lua += `    defaultSettings = {\n`;
    for (const [key, value] of Object.entries(addon.defaultSettings)) {
      const keyStr = `["${escapeLuaString(key)}"] = `;
      if (typeof value === 'boolean') {
        lua += `      ${keyStr}${value},\n`;
      } else if (typeof value === 'number') {
        lua += `      ${keyStr}${value},\n`;
      } else if (typeof value === 'string') {
        lua += `      ${keyStr}"${escapeLuaString(value)}",\n`;
      } else {
        lua += `      ${keyStr}nil,\n`;
      }
    }
    lua += `    },\n`;
  }

  lua += `  }`;
  return lua;
}

// ============================================================================
// Generate Data.lua
// ============================================================================
let output = `--[[
  This file is auto-generated by scripts/generate_lua_tables.mjs.
  Do NOT edit manually — regenerate with \`node scripts/generate_lua_tables.mjs\`.
]]

CAPClasses = {\n`;

for (const classInfo of classesData.classes) {
  output += generateClassTable(classInfo);
}
output += `}\n\n`;

// Generate CAPAddonRegistry from shared registry data
output += `--[[
  Addon detection and auto-configuration registry.
  Generated from shared/registry-addons.json — edit the source in
  shared/addon-recommendations.ts REGISTRY_ADDONS and re-run the generator.
]]

CAPAddonRegistry = {\n`;

for (const addon of registryAddons) {
  output += generateAddonEntry(addon.key, addon);
  output += ',\n';
}

output += `}\n\n`;

// Utility function — stays in Data.lua regardless of generator state
output += `--[[
  Get all class/spec keys as a flat array.
]]
function CAP:GetAllClassSpecKeys()
  local result = {}
  for classId, classData in pairs(CAPClasses) do
    for specId in pairs(classData.specs) do
      table.insert(result, classId .. "_" .. specId)
    end
  end
  return result
end\n`;

writeFileSync(resolve(__dirname, '..', 'addon', 'Data.lua'), output);
console.log('Generated addon/Data.lua');
console.log(`  - ${classesData.classes.length} classes`);
console.log(`  - ${registryAddons.length} addons in registry`);
